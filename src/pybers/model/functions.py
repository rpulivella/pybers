#!/usr/bin/env python3
"""\
Names for the function indices a formula stores, in both directions.

A `.numbers` package records a call as a bare number, so `SUM` is 168 and nothing
in the file says so. The map comes from the Numbers application binary, is
committed under `pybers._generated`, and is regenerated by
`scripts/functions-extract.py`, which reports what changed rather than replacing
it silently.

**The index is what the file holds, and the name is a convenience over it.**
Nothing here converts a call for storage: `FormulaFunctionCall` carries an index
either way, so a formula authored by name and one authored by index write the
same bytes. That is why an unnamed function is a `None` rather than an error, and
why it round-trips untouched.

The map covers what Numbers' own authoring code names, which on 15.3.1 is 324 of
the 350 functions it lists. `scripts/functions-extract.py --gaps` names the rest.

UPDATES
2026-09-04  Written for #44.
"""
