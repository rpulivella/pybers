__license__ = "Apache-2.0"
__version__ = "0.1.0"
__email__ = "pybers@richardulivella.com"
__status__ = "Development"
__date__ = "2026/09/04"

from types import MappingProxyType
from typing import Final

from pybers._generated.functions import functionNames as generatedNames

# Read-only views, because one shared dictionary handed out mutable is the same
# defect the frozen `Style` contract exists to prevent: an edit at one call site
# would silently rename a function everywhere.
functionNames: Final[MappingProxyType[int, str]] = MappingProxyType(
    dict(generatedNames)
)

functionIndices: Final[MappingProxyType[str, int]] = MappingProxyType(
    {name: index for index, name in generatedNames.items()}
)


class UnknownFunctionError(ValueError):
    """A function name the map does not carry, named where an index was needed."""


def functionNameFor(index: int) -> str | None:
    """Return the name of a function index, or None when the map does not carry it."""
    return functionNames.get(index)


def functionIndexFor(name: str) -> int:
    """Return the index of a function named as Numbers spells it, `SUM` or `sum`.

    Raises rather than guessing, because an index invented for an unknown name
    would write a formula calling some other function.
    """
    index = functionIndices.get(name.strip().upper())
    if index is None:
        raise UnknownFunctionError(
            f"{name!r} is not a function this map names. Either Numbers does not "
            "have it, or it is one of the functions no authoring method names; "
            "run scripts/functions-extract.py --gaps to see which. Construct "
            "FormulaFunctionCall with the index directly if you know it."
        )
    return index
